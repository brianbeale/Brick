// ── Slot ─────────────────────────────────────────────────────────────────────

/// An injectable UI content slot — an opaque, cheaply-cloneable handle to a
/// rendered sub-tree. Declare on a model field with `#[slot]` and create at
/// the call site with the `slot!` macro.
///
/// ```rust,ignore
/// Card { title: "Settings", children: slot!(row! { button("Save"), button("Cancel") }), ..cascade() }
/// ```
pub struct Slot(std::rc::Rc<dyn Brick>);

impl Slot {
    #[allow(dead_code)]
    pub fn from_component(c: Box<dyn Brick>) -> Self {
        Slot(std::rc::Rc::from(c))
    }
}

impl Clone for Slot {
    fn clone(&self) -> Self {
        Slot(std::rc::Rc::clone(&self.0))
    }
}

impl Default for Slot {
    fn default() -> Self {
        Slot(std::rc::Rc::new(EmptySlot))
    }
}

impl From<Box<dyn Brick>> for Slot {
    fn from(b: Box<dyn Brick>) -> Self {
        Slot(std::rc::Rc::from(b))
    }
}

impl Brick for Slot {
    fn render_into(&self, parent: &crate::renderer::BrickNode) {
        self.0.render_into(parent);
    }
    fn detach(&self) {
        self.0.detach();
    }
}

// Use &Slot so that field access through Deref (which yields &Slot, not owned Slot)
// works without requiring a move. Cloning an Rc is cheap. Owned Slot bindings
// auto-ref to &Slot transparently.
impl IntoComponent for &Slot {
    fn into_component(self) -> Box<dyn Brick> {
        Box::new(self.clone())
    }
}

struct EmptySlot;
impl Brick for EmptySlot {
    fn render_into(&self, parent: &crate::renderer::BrickNode) {
        use crate::renderer::{BrickRenderer as _, Renderer};
        Renderer::append(parent, &Renderer::text(""));
    }
}

/// Escape `&`, `<`, `>` so a plain string is safe to place inside an HTML element.
pub fn escape_html(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

// ── Scoped style injection ────────────────────────────────────────────────────

/// The `#[view]` macro stores the current component's instance class here so
/// that the `style!` declarative macro can read it without hygiene conflicts.
/// WASM is single-threaded so this is always safe; native test builds are also
/// fine because each test thread gets its own copy.
pub(crate) fn set_scope(class: &str) {
    BRICK_SCOPE.with(|s| *s.borrow_mut() = class.to_owned());
}

pub(crate) fn get_scope() -> String {
    BRICK_SCOPE.with(|s| s.borrow().clone())
}

thread_local! {
    static BRICK_SCOPE: std::cell::RefCell<String> = const { std::cell::RefCell::new(String::new()) };
}

/// Prefix each CSS selector in `css` with `.{scope}` and inject a `<style>`
/// element into the document. Called at render time by the `style!` macro.
/// No-op in test builds (no DOM available).
pub fn inject_scoped_style(css: &str, scope: &str) {
    let _ = (css, scope);
    #[cfg(brick_dom)]
    {
        use wasm_bindgen::JsCast;
        let scoped = scope_css(css, scope);
        let document = web_sys::window().unwrap().document().unwrap();
        let style_el = document.create_element("style").unwrap();
        style_el.set_inner_html(&scoped);
        document
            .body()
            .unwrap()
            .append_child(style_el.unchecked_ref())
            .unwrap();
    }
}

/// Wrap a DOM-mutating callback in `document.startViewTransition()` when available,
/// falling back to a direct call when the API is absent. No-op wrapper in test builds.
#[cfg(brick_dom)]
pub(crate) fn start_view_transition(callback: impl FnOnce() + 'static) {
    use wasm_bindgen::JsCast;
    use wasm_bindgen::closure::Closure;
    let doc = web_sys::window().unwrap().document().unwrap();
    let start_vt = js_sys::Reflect::get(&doc, &"startViewTransition".into())
        .ok()
        .and_then(|v| v.dyn_into::<js_sys::Function>().ok());
    if let Some(f) = start_vt {
        let cb = Closure::once(callback);
        let _ = f.call1(&doc, cb.as_ref().unchecked_ref());
        cb.forget();
    } else {
        callback();
    }
}

/// Inject a raw CSS string into the page without any selector scoping.
/// Used by `keyframes!` and `Keyframes::inject()`. No-op in test builds.
pub fn inject_global_style(css: &str) {
    let _ = css;
    #[cfg(brick_dom)]
    {
        use wasm_bindgen::JsCast;
        let document = web_sys::window().unwrap().document().unwrap();
        let style_el = document.create_element("style").unwrap();
        style_el.set_inner_html(css);
        document
            .body()
            .unwrap()
            .append_child(style_el.unchecked_ref())
            .unwrap();
    }
}

fn scope_css(css: &str, scope: &str) -> String {
    let mut result = String::new();
    for block in css.split('}') {
        let block = block.trim();
        if block.is_empty() {
            continue;
        }
        if let Some(brace) = block.find('{') {
            let selectors = block[..brace].trim();
            let declarations = block[brace + 1..].trim();
            let scoped: String = selectors
                .split(',')
                .map(|s| format!(".{} {}", scope, s.trim()))
                .collect::<Vec<_>>()
                .join(", ");
            result.push_str(&scoped);
            result.push_str(" { ");
            result.push_str(declarations);
            result.push_str(" }\n");
        }
    }
    result
}

// ── CSS-on-mount deferred callbacks ──────────────────────────────────────────

/// Called by the `style!` proc macro to register reactive CSS custom property
/// observers. Closures are drained by `make_composite!` into `ViewComposite::on_mount`.
pub fn push_css_on_mount(f: Box<dyn Fn()>) {
    CSS_ON_MOUNT.with(|v| v.borrow_mut().push(std::rc::Rc::from(f)));
}

pub(crate) fn drain_css_on_mount() -> Vec<std::rc::Rc<dyn Fn()>> {
    CSS_ON_MOUNT.with(|v| v.borrow_mut().drain(..).collect())
}

/// Set a CSS custom property on the component scope element. Called by closures
/// emitted by `style!` for `{expr:spec}unit` dynamic values.
#[cfg(brick_dom)]
pub fn set_css_var_on_scope(scope: &str, var_name: &str, value: &str) {
    use wasm_bindgen::JsCast;
    if let Some(window) = web_sys::window() {
        if let Some(document) = window.document() {
            let selector = format!(".{}", scope);
            if let Ok(Some(el)) = document.query_selector(&selector) {
                let html_el = el.unchecked_into::<web_sys::HtmlElement>();
                let _ = html_el.style().set_property(var_name, value);
            }
        }
    }
}

thread_local! {
    static CSS_ON_MOUNT: std::cell::RefCell<Vec<std::rc::Rc<dyn Fn()>>> =
        const { std::cell::RefCell::new(Vec::new()) };
}

