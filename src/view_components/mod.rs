pub trait Brick {
    fn render_into(&self, parent: &crate::renderer::BrickNode);
    fn attach_listeners(&self) {}
    fn detach(&self) {}
    fn is_fragment(&self) -> bool {
        false
    }
}

impl<T: Brick + ?Sized> Brick for Box<T> {
    fn render_into(&self, parent: &crate::renderer::BrickNode) {
        (**self).render_into(parent);
    }
    fn attach_listeners(&self) {
        (**self).attach_listeners();
    }
    fn detach(&self) {
        (**self).detach();
    }
    fn is_fragment(&self) -> bool {
        (**self).is_fragment()
    }
}

/// Render a component to an HTML string. Creates a temporary container, calls
/// `render_into`, and serialises the container's children. Used everywhere an
/// HTML string is needed (SSR, DOM `set_inner_html` bridges, tests).
pub fn render_to_html(brick: &dyn Brick) -> String {
    use crate::renderer::{BrickRenderer as _, HtmlRenderer};
    let parent = HtmlRenderer::element("div");
    brick.render_into(&parent);
    parent.inner_html_string()
}

/// Type-erase a `Brick` into a heap allocation.
pub trait IntoBrick {
    fn into_brick(self) -> Box<dyn Brick>;
}

impl<T: Brick + Sized + 'static> IntoBrick for Box<T> {
    fn into_brick(self) -> Box<dyn Brick> {
        self
    }
}

impl IntoBrick for Box<dyn Brick> {
    fn into_brick(self) -> Box<dyn Brick> {
        self
    }
}

/// Anything that can be placed as a child in `children!` or `row!`, or mounted
/// at the application root.
///
/// Implemented automatically for:
/// - `Box<T: Brick>` — all element builders and containers
/// - `Box<dyn Brick>` — already-erased components
/// - Concrete component model structs — `impl IntoComponent` generated by `#[view]`
pub trait IntoComponent {
    fn into_component(self) -> Box<dyn Brick>;

    /// Render and mount this component into a DOM element, wiring all event
    /// listeners. Event wiring is a no-op outside `brick_dom` builds.
    fn mount(self, slot: &web_sys::HtmlElement)
    where
        Self: Sized,
    {
        let component = self.into_component();
        slot.set_inner_html(&crate::view_components::render_to_html(&*component));
        component.attach_listeners();
    }
}

impl IntoComponent for Box<dyn Brick> {
    fn into_component(self) -> Box<dyn Brick> {
        self
    }
}

impl<T: Brick + Sized + 'static> IntoComponent for Box<T> {
    fn into_component(self) -> Box<dyn Brick> {
        self
    }
}
