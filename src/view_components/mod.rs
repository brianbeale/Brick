#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escape_html_replaces_special_chars() {
        assert_eq!(escape_html("<b>a & b</b>"), "&lt;b&gt;a &amp; b&lt;/b&gt;");
    }

    #[test]
    fn escape_html_passthrough_plain_text() {
        assert_eq!(escape_html("hello world"), "hello world");
    }

    #[test]
    fn scope_css_prefixes_selector() {
        let out = scope_css("p { color: red }", "my-scope");
        assert_eq!(out.trim(), ".my-scope p { color: red }");
    }

    #[test]
    fn scope_css_handles_multi_selector() {
        let out = scope_css("h1, h2 { margin: 0 }", "s");
        assert!(out.contains(".s h1") && out.contains(".s h2"));
    }

    #[test]
    fn scope_css_empty_input() {
        assert_eq!(scope_css("", "s"), "");
    }
}
